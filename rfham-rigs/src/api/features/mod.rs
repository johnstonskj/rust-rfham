use crate::{Level, VfoLabel, error::RigError};
use serde::{Deserialize, Serialize};
use strum::{AsRefStr, Display, EnumIs, EnumIter, EnumString};

// ------------------------------------------------------------------------------------------------
// Public Macros
// ------------------------------------------------------------------------------------------------

// ------------------------------------------------------------------------------------------------
// Public Types ❯ Base Traits
// ------------------------------------------------------------------------------------------------

#[derive(
    Clone,
    Copy,
    Debug,
    PartialEq,
    Eq,
    PartialOrd,
    Ord,
    Deserialize,
    Serialize,
    AsRefStr,
    Display,
    EnumIs,
    EnumString,
    EnumIter,
)]
pub enum Features {
    AfGainControl,
    AntennaSwitching,
    VfoAandB,
}

pub trait Feature {
    const FEATURE_ID: Features;
}

// ------------------------------------------------------------------------------------------------
// Public Types ❯ Has AF Gain Control
// ------------------------------------------------------------------------------------------------

pub trait AfGainControl: Feature {
    const FEATURE_ID: Features = Features::AfGainControl;

    fn level(&self) -> Result<(), RigError>;
    fn set_level(&mut self, level: Level) -> Result<(), RigError>;
}

// ------------------------------------------------------------------------------------------------
// Public Types ❯ Has Antenna Switching
// ------------------------------------------------------------------------------------------------

pub trait AntennaSwitching: Feature {
    const FEATURE_ID: Features = Features::AntennaSwitching;

    fn antenna_count(&self) -> Result<usize, RigError>;
    fn antenna(&self, antenna: usize) -> Result<(), RigError>;
    fn current_antenna(&self) -> Result<usize, RigError>;
    fn set_current_antenna(&self, antenna: usize) -> Result<(), RigError>;
}

// ------------------------------------------------------------------------------------------------
// Public Types ❯ Has VFO-A and VFO-B
// ------------------------------------------------------------------------------------------------

pub trait VfoAandB: Feature {
    const FEATURE_ID: Features = Features::VfoAandB;

    fn vfo(&self, vfo: VfoLabel) -> Result<(), RigError>;
    fn set_current(&self, vfo: VfoLabel) -> Result<(), RigError>;
}

